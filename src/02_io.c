/* 02_io 格式化输入输出与类型 | ISO C99 | 基础
 * 来源/关系：S2 编程1–2；S4 p2（页码均为 PDF 页码；此文件为重写的教学实现）
 * 输入输出约定：输入整数a与实数r，|a|<=10000、0<=r<=10000；输出a平方、圆面积和周长（PI=3.14）
 * 思想：scanf需要对象地址，printf需要值；double输入用%lf。
 * 复杂度：O(1)
 * 练习：换一组边界数据，先手算再运行。
 * 学习顺序：先看题目→手算样例→遮住代码独立写→运行测试→比较另一语言。
 * 对照：同目录 02_io.cpp 用 cin/cout 和 fixed/setprecision 代替格式串。
 */
#include <stdio.h> /* 声明scanf和printf；C++版用输入输出流。 */
int main(void) { /* C程序入口。 */
    int a; /* 保存要计算平方的整数。 */
    double r; /* 保存圆的半径。 */
    if (scanf("%d%lf", &a, &r) != 2 || a < -10000 || a > 10000 || !(r >= 0 && r <= 10000))
        return 1; /* 读取失败或范围不合法时退出；scanf需要变量地址。 */
    const double pi = 3.14; /* 按题目指定的圆周率计算。 */
    printf("%d %.2f %.2f\n", a * a, pi * r * r, 2 * pi * r); /* 依次输出平方、面积和周长。 */
    return 0; /* 表示程序正常结束。 */
}
