/* 06_digits 数位拆分、水仙花数 | ISO C99 | 基础
 * 来源/关系：S1 p22 编程12、p120 编程1；S5 p6–7 水仙花数（页码均为 PDF
 * 页码；此文件为重写的教学实现）
 * 输入输出约定：输入0..999999999；输出位数、数字和、倒序数字；再输出所有三位水仙花数
 * 思想：模10取末位，除10删末位；do-while正确处理0。
 * 复杂度：O(log n)，枚举三位数为常数工作
 * 练习：换一组边界数据，先手算再运行。
 * 学习顺序：先看题目→手算样例→遮住代码独立写→运行测试→比较另一语言。
 * C++对照：同目录06_digits.cpp使用cin/cout和bool；本版使用scanf/printf和整数标志。
 */
#include <stdio.h> /* 声明scanf、printf和putchar。 */
int main(void) { /* C程序入口。 */
    long long n; /* 保存待拆分的非负整数。 */
    if (scanf("%lld", &n) != 1 || n < 0 || n > 999999999)
        return 1; /* 读取失败或超出范围时退出。 */
    int count = 0, sum = 0; /* 依次记录已处理的位数与数字和。 */
    long long reversed = 0; /* 保存从右向左拼出的倒序数字。 */
    do { /* 至少执行一次，因此输入0也能正确算出一位。 */
        int digit = (int)(n % 10); /* 取当前末位，值在0至9之间。 */
        sum += digit; /* 加入数字和。 */
        reversed = reversed * 10 + digit; /* 原结果左移一位后接上当前数字。 */
        ++count; /* 多处理了一位。 */
        n /= 10; /* 删除刚处理的末位。 */
    } while (n); /* 还有更高位时继续。 */
    printf("%d %d %lld\n", count, sum, reversed); /* 输出位数、数字和和倒序值。 */
    int first = 1; /* 控制第一个水仙花数前没有空格。 */
    for (int x = 100; x <= 999; ++x) { /* 枚举每个三位数。 */
        int a = x / 100, b = x / 10 % 10, c = x % 10; /* 取百位、十位、个位。 */
        if (a * a * a + b * b * b + c * c * c == x) { /* 三位立方和等于原数。 */
            printf("%s%d", first ? "" : " ", x); /* 首项不带前导空格。 */
            first = 0; /* 后续输出前需要分隔空格。 */
        }
    }
    putchar('\n'); /* 结束水仙花数所在行。 */
    return 0; /* 表示程序正常结束。 */
}
