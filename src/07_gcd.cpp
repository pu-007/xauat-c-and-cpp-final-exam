/* 07_gcd 欧几里得算法与最小公倍数 | ISO C++11 | 基础
 * 来源/关系：S1 p22 编程11；算法优化（页码均为 PDF 页码；此文件为重写的教学实现）
 * 输入输出约定：输入0..10^9的两个整数；输出gcd和lcm；约定gcd(0,0)=0
 * 思想：gcd(a,b)=gcd(b,a%b)；lcm先除后乘以降低溢出风险。
 * 复杂度：O(log(min(a,b)+1))
 * 练习：换一组边界数据，先手算再运行。
 * 学习顺序：先看题目→手算样例→遮住代码独立写→运行测试→比较另一语言。
 * C对照：同目录07_gcd.c用scanf/printf；C++11没有std::gcd，两版都手写递推。
 */
#include <iostream> // 声明cin和cout；C版使用stdio.h。
long long gcd(long long a, long long b) { // 返回两个非负整数的最大公约数。
    while (b) { // 除数为0时结束，避免取余除以0。
        long long t = a % b; // 保存余数，公约数集合不变。
        a = b; // 原除数成为下一轮被除数。
        b = t; // 余数成为下一轮除数。
    }
    return a; // 最后一个非零除数是最大公约数；两数为0时返回0。
}
int main() { // C++程序入口。
    long long a, b; // 两个非负输入。
    if (!(std::cin >> a >> b) || a < 0 || b < 0 || a > 1000000000 || b > 1000000000)
        return 1; // 读取失败或超出范围时退出。
    long long g = gcd(a, b); // 调用辗转相除函数。
    std::cout << g << ' ' << (g == 0 ? 0 : a / g * b) << '\n'; // 两数均为0时避开除零，否则先除后乘。
} // main自然结束时返回0。
