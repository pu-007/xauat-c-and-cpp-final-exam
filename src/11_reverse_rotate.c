/* 11_reverse_rotate 逆序、循环右移、最小最大交换 | ISO C99 | 提高
 * 来源/关系：S5 p5 例8.8、p8 习题3；S1 p61 编程2/3（页码均为 PDF 页码；此文件为重写的教学实现）
 * 输入输出约定：n=1..100,k=0..10^9，再输入n个int；先右移k位输出，再将最小换到首、最大换到尾后输出
 * 思想：三次反转实现旋转；交换后旧的极值位置可能失效，重新查找最大值。
 * 复杂度：O(n)，C版额外空间O(1)
 * 对照 11_reverse_rotate.cpp：C 手写反转与指针交换，C++ 使用 rotate 和迭代器。
 * 练习：换一组边界数据，先手算再运行。
 * 学习顺序：先看题目→手算样例→遮住代码独立写→运行测试→比较另一语言。
 */
#include <stdio.h> /* scanf、printf、putchar；C++ 使用 cin、cout。 */
static void swap(int *x, int *y) {
    /* 暂存 x 指向的值，再依次写入两个对象。 */
    int t = *x; /* 保存左侧值。 */
    *x = *y; /* 将右侧值写入左侧。 */
    *y = t; /* 暂存值写入右侧。 */
}
static void reverse(int a[], int left, int right) {
    /* 区间两端向中间收缩；空区间（例如 k=0）不执行。 */
    while (left < right) /* 两端相遇即结束。 */
        swap(&a[left++], &a[right--]); /* 交换当前两端后各向内走一格。 */
}
static void print(const int a[], int n) {
    /* 首元素不输出前导空格，最后统一换行。 */
    for (int i = 0; i < n; ++i) /* 逐个输出。 */
        printf("%s%d", i ? " " : "", a[i]); /* 首项无前导空格。 */
    putchar('\n'); /* 结束当前行。 */
}
int main(void) {
    /* 先验证长度和移位数，再读取恰好 n 个整数。 */
    int n, k, a[100]; /* 个数、位数和输入数组。 */
    if (scanf("%d%d", &n, &k) != 2 || n < 1 || n > 100 || k < 0 || k > 1000000000)
        return 1; /* 防止空数组、越界和负位数。 */
    for (int i = 0; i < n; ++i) /* 读取 n 项。 */
        if (scanf("%d", &a[i]) != 1)
            return 1; /* 输入不完整。 */
    /* 归约移位数，整体反转后分别反转两个部分。 */
    k %= n; /* 整圈旋转不影响结果。 */
    reverse(a, 0, n - 1); /* 整体反转。 */
    reverse(a, 0, k - 1); /* 恢复原末尾 k 项的顺序。 */
    reverse(a, k, n - 1); /* 恢复其余项的顺序。 */
    print(a, n); /* 第一行是旋转结果。 */
    /* 严格比较使并列最小值选择第一次出现者。 */
    int lo = 0; /* 首项作为初始最小值。 */
    for (int i = 1; i < n; ++i) /* 扫描剩余元素。 */
        if (a[i] < a[lo]) /* 相等时不覆盖首个位置。 */
            lo = i; /* 保存更小值的下标。 */
    swap(&a[0], &a[lo]); /* 最小值换到首项。 */
    /* 首次交换可能移动最大值，因此从头重新查找。 */
    int hi = 0; /* 从交换后的首项开始。 */
    for (int i = 1; i < n; ++i) /* 重新扫描。 */
        if (a[i] > a[hi]) /* 保留首个最大值。 */
            hi = i;
    swap(&a[n - 1], &a[hi]); /* 最大值换到末项。 */
    /* 输出第二次交换后的结果。 */
    print(a, n); /* 输出调整后的数组。 */
    return 0; /* 正常结束。 */
}
