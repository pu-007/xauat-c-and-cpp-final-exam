/* 14_matrix 二维数组、转置、对角线、行列极值 | ISO C99 | 提高
 * 来源/关系：S1 p32 编程8/10、p42 编程4；S5 p3/p4（页码均为 PDF 页码；此文件为重写的教学实现）
 * 输入输出约定：输入3×3整数矩阵，元素绝对值<=10^6；输出转置矩阵、去重对角和、最大值及行列（从0起）
 * 思想：a+i跨一行，a[i]+j跨一个元素；对角线交点只加一次。
 * 复杂度：推广n×n时O(n²)
 * 对照 14_matrix.cpp：C 使用二维数组参数，C++ 使用可按值返回的 std::array。
 * 练习：换一组边界数据，先手算再运行。
 * 学习顺序：先看题目→手算样例→遮住代码独立写→运行测试→比较另一语言。
 */
#include <stdio.h> /* scanf、printf、putchar；C++ 使用流。 */
static void transpose(const int a[3][3], int b[3][3]) {
    /* 对每个元素交换行、列下标写入新矩阵。 */
    for (int i = 0; i < 3; ++i) /* 遍历行。 */
        for (int j = 0; j < 3; ++j) /* 遍历列。 */
            b[j][i] = a[i][j]; /* 输出矩阵的行列互换。 */
}
int main(void) {
    /* 逐行读取并限制元素范围。 */
    int a[3][3], b[3][3]; /* 原矩阵和转置矩阵。 */
    for (int i = 0; i < 3; ++i) /* 依次读取每行。 */
        for (int j = 0; j < 3; ++j) /* 依次读取每列。 */
            if (scanf("%d", &a[i][j]) != 1 || a[i][j] < -1000000 || a[i][j] > 1000000)
                return 1; /* 失败或越界则退出。 */
    /* C99给多维数组添加const限定存在转换限制，用显式指向const行的转换。 */
    transpose((const int (*)[3])a, b); /* 计算转置并写入 b。 */
    /* 对角和用宽整数，最大值先取左上角。 */
    long long diagonal = 0; /* 对角线和。 */
    int r = 0, c = 0; /* 暂以首元素为最大值。 */
    for (int i = 0; i < 3; ++i) { /* 逐行处理。 */
        /* 输出转置的当前行，同时扫描原矩阵。 */
        for (int j = 0; j < 3; ++j) { /* 逐列处理。 */
            printf("%s%d", j ? " " : "", b[i][j]); /* 首列不加前导空格。 */
            /* 逻辑或保证两条对角线的交点只计一次。 */
            if (i == j || i + j == 2) /* 任一对角线上。 */
                diagonal += a[i][j]; /* 原矩阵该元素只计一次。 */
            /* 仅严格更大时更新，保留首个最大值。 */
            if (a[i][j] > a[r][c]) { /* 找到更大的元素。 */
                r = i; /* 更新行。 */
                c = j; /* 更新列。 */
            }
        }
        putchar('\n'); /* 一行转置输出结束。 */
    }
    /* 输出去重对角和及最大值的零起始坐标。 */
    printf("%lld\n%d %d %d\n", diagonal, a[r][c], r, c); /* 和及最大值坐标。 */
    return 0; /* 正常结束。 */
}
