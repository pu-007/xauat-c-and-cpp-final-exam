/* 14_matrix 二维数组、转置、对角线、行列极值 | ISO C++11 | 提高
 * 来源/关系：S1 p32 编程8/10、p42 编程4；S5 p3/p4（页码均为 PDF 页码；此文件为重写的教学实现）
 * 输入输出约定：输入3×3整数矩阵，元素绝对值<=10^6；输出转置矩阵、去重对角和、最大值及行列（从0起）
 * 思想：a+i跨一行，a[i]+j跨一个元素；对角线交点只加一次。
 * 复杂度：推广n×n时O(n²)
 * 对照 14_matrix.c：C 使用二维数组与输出参数，C++ 使用 std::array 返回矩阵。
 * 练习：换一组边界数据，先手算再运行。
 * 学习顺序：先看题目→手算样例→遮住代码独立写→运行测试→比较另一语言。
 */
#include <iostream> // cin、cout 对应 C 的 scanf、printf。
#include <array> // std::array 可按值返回；C 用二维数组输出参数。
using Matrix = std::array<std::array<int, 3>, 3>; // 三个三元素数组组成矩阵。
// const 引用避免复制输入；返回值是独立的转置矩阵。
Matrix transpose(const Matrix &a) {
    Matrix b{}; // 初始化输出矩阵。
    // 遍历每个原元素并把行列对调。
    for (int i = 0; i < 3; ++i) // 遍历原矩阵的行。
        for (int j = 0; j < 3; ++j) // 遍历列。
            b[j][i] = a[i][j]; // 行列对调。
    return b; // 返回转置后的矩阵值。
}
int main() {
    // 逐行通过引用读取，确保每个元素都在允许范围。
    Matrix a{}; // 保存输入。
    for (auto &row : a) // 依次访问每行。
        for (int &x : row) // 引用每个实际元素。
            if (!(std::cin >> x) || x < -1000000 || x > 1000000)
                return 1; // 输入缺失或不在范围内。
    auto b = transpose(a); // 得到独立转置矩阵。
    // 和用宽整数；以左上角作为最大值初始位置。
    long long diagonal = 0; // 存储对角线和。
    int r = 0, c = 0; // 先以首元素为最大值。
    for (int i = 0; i < 3; ++i) { // 扫描行。
        // 输出转置行，同时检查原矩阵对应位置。
        for (int j = 0; j < 3; ++j) { // 扫描列。
            std::cout << (j ? " " : "") << b[i][j]; // 输出转置元素。
            // 两条对角线取并集，交点只加一次。
            if (i == j || i + j == 2) // 位于任一对角线。
                diagonal += a[i][j]; // 两线交点也只加一次。
            // 仅在更大时替换坐标，重复值保留首个。
            if (a[i][j] > a[r][c]) { // 找到更大值。
                r = i; // 保存行坐标。
                c = j; // 保存列坐标。
            }
        }
        std::cout << '\n'; // 结束当前行。
    }
    // 输出和、最大值及其行列下标。
    std::cout << diagonal << '\n' << a[r][c] << ' ' << r << ' ' << c << '\n';
}
