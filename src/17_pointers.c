/* 17_pointers 值传递、指针、数组指针 | ISO C99 | 提高
 * 来源/关系：S1 p43–61；S2 函数/指针读程序；S4 p4（页码均为 PDF 页码；此文件为重写的教学实现）
 * 输入输出约定：无输入；输出值传递后原值、指针交换后值、指针步进及二维访问
 * 思想：C所有参数均按值传递；传地址让函数能间接修改调用者对象。
 * 复杂度：O(1)
 * 对照 17_pointers.cpp：C 用地址交换调用者的值，C++ 还可以使用引用。
 * 练习：换一组边界数据，先手算再运行。
 * 学习顺序：先看题目→手算样例→遮住代码独立写→运行测试→比较另一语言。
 */
#include <stdio.h> /* printf 输出结果；C++ 对应 cout。 */
static void wrong_swap(int a, int b) {
    /* 参数是副本，三次赋值不会改变调用者的 x、y。 */
    int t = a; /* 保存第一个副本。 */
    a = b; /* 第二个副本赋给第一个。 */
    b = t; /* 原第一个副本赋给第二个。 */
    /* 显式标记副本已使用，避免仅赋值未使用的警告。 */
    (void)a;
    (void)b;
}
static void swap(int *a, int *b) {
    /* 解引用地址，交换的是调用者对象本身。 */
    int t = *a; /* 保存 a 指向的原值。 */
    *a = *b; /* 将 b 指向的值写入 a 指向的位置。 */
    *b = t; /* 恢复保存的值到 b 指向的位置。 */
}
int main(void) {
    /* 先比较值传递和传地址两种调用结果。 */
    int x = 3, y = 7; /* 调用者的两个对象。 */
    wrong_swap(x, y); /* 按值传递，原对象不变。 */
    printf("%d %d\n", x, y); /* 输出 3 7。 */
    swap(&x, &y); /* 传入对象地址。 */
    printf("%d %d\n", x, y); /* 输出交换后的 7 3。 */
    /* 数组名在此转换为指向首元素的指针。 */
    int a[] = {10, 20, 30}; /* 三个连续整数。 */
    int *p = a; /* 初始指向首元素。 */
    int old = *p++; /* 等价于*(p++)：读10，再让p指向a[1]。 */
    /* p 已指向第二项，对该项自增而不是移动指针。 */
    (*p)++; /* 将第二项从 20 改为 21。 */
    printf("%d %d %d\n", old, *p, a[1]); /* 后两项引用同一对象。 */
    /* row 的步长是一整行 3 个 int，不是单个 int。 */
    int m[2][3] = {{1, 2, 3}, {4, 5, 6}}; /* 两行三列。 */
    int (*row)[3] = m; /* 指向首行的数组指针。 */
    /* 行指针前进一步，再取该行下标 2，与 m[1][2] 相同。 */
    printf("%d %d\n", *(*(row + 1) + 2), m[1][2]);
    return 0;
}
