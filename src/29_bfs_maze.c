/* 29_bfs_maze 迷宫广度优先搜索 | ISO C99 | 拓展
 * 来源/关系：S1 p95 附加82：寻找路径的最短路拓展（页码均为 PDF 页码；此文件为重写的教学实现）
 * 输入输出约定：行列1..20；矩阵0可走、1墙；从左上到右下四方向；输出最少步数，不通为-1
 * 思想：队列按距离分层；入队时标记，保证每格只入队一次。
 * 复杂度：O(行×列)，空间同阶
 * 对照 29_bfs_maze.cpp：C 用定长数组模拟队列，C++ 用 vector 和 queue。
 * 练习：增加前驱数组恢复路径；有权边不能直接套普通BFS。
 * 学习顺序：先看题目→手算样例→遮住代码独立写→运行测试→比较另一语言。
 */
#include <stdio.h> /* 声明 scanf 和 printf；C++ 使用 cin、cout。 */
int main(void) {
    int rows, cols, a[20][20], dist[20][20], qr[400], qc[400]; /* 网格、距离和队列坐标。 */
    if (scanf("%d%d", &rows, &cols) != 2 || rows < 1 || rows > 20 || cols < 1 || cols > 20) /* 检查尺寸。 */
        return 1; /* 尺寸不合法，退出。 */
    for (int r = 0; r < rows; ++r) /* 逐行读入。 */
        for (int c = 0; c < cols; ++c) { /* 逐列检查格子。 */
            if (scanf("%d", &a[r][c]) != 1 || (a[r][c] != 0 && a[r][c] != 1)) /* 只允许 0 和 1。 */
                return 1; /* 格子输入不合法，退出。 */
            dist[r][c] = -1; /* -1 同时表示未访问和最终不可达。 */
        }
    int head = 0, tail = 0; /* 队首索引和下一空位，初始队列为空。 */
    const int dr[] = {1, -1, 0, 0}, dc[] = {0, 0, 1, -1}; /* 四个方向的行列增量。 */
    if (a[0][0] == 0) { /* 起点为墙时不入队。 */
        qr[tail] = 0; /* 写入起点行。 */
        qc[tail++] = 0; /* 写入起点列并推进队尾。 */
        dist[0][0] = 0; /* 起点到自身需要零步。 */
    }
    while (head < tail) { /* 只要队列非空就处理下一格。 */
        int r = qr[head], c = qc[head++]; /* 取出队首并推进队首。 */
        for (int d = 0; d < 4; ++d) { /* 尝试每个相邻方向。 */
            int nr = r + dr[d], nc = c + dc[d]; /* 计算邻格坐标。 */
            if (nr >= 0 && nr < rows && nc >= 0 && nc < cols && !a[nr][nc] && dist[nr][nc] == -1) { /* 限制在可走且未访问的格子。 */
                dist[nr][nc] = dist[r][c] + 1; /* 首次发现即最短距离。 */
                qr[tail] = nr; /* 写入邻格行。 */
                qc[tail++] = nc; /* 写入邻格列并入队。 */
            }
        }
    }
    printf("%d\n", dist[rows - 1][cols - 1]); /* 未到达时仍为 -1。 */
    return 0; /* 正常结束。 */
}
