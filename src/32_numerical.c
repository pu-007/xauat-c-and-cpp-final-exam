/* 32_numerical 数值迭代：莱布尼茨级数与牛顿法 | ISO C99 | 提高
 * 来源/关系：S5 p1–2 求π；S1 p23 编程22的求根变式（页码均为 PDF 页码；此文件为重写的教学实现）
 * 输入输出约定：输入x，0<=x<=10^12；输出牛顿法sqrt(x)及以原资料1e-6项阈值求得的π（六位小数）
 * 思想：递推避免重复运算；迭代要有容差和次数上限；项误差不等于最终π误差。
 * 复杂度：平方根至多1100次迭代；π约500000项，空间O(1)。
 * 对照 32_numerical.cpp：C 使用 math.h 的 fabs 和 printf，C++ 使用标准库流。
 * 练习：把sqrt结果与库函数比较；解释为何不能声称π精确到小数点后8位。
 * 学习顺序：先看题目→手算样例→遮住代码独立写→运行测试→比较另一语言。
 */
#include <stdio.h> /* 提供 scanf、printf；C++ 对照使用输入输出流。 */
#include <math.h> /* 提供浮点绝对值 fabs；C++ 对照使用 std::abs。 */
int main(void) {
    double x; /* 需要计算平方根的非负数。 */
    if (scanf("%lf", &x) != 1 || !(x >= 0 && x <= 1e12)) /* 同时排除范围外及 NaN。 */
        return 1; /* 输入无效，退出。 */
    double root = x > 1 ? x : 1; /* 非零输入从正数开始，避免除零。 */
    if (x == 0) /* 零的平方根直接确定。 */
        root = 0; /* 零的平方根为零。 */
    else
        for (int i = 0; i < 1100; ++i) { /* 极小正数也有足够迭代次数。 */
            double next = (root + x / root) / 2; /* 牛顿法求 root²=x 的下一近似。 */
            if (fabs(next - root) <= 1e-12 * fabs(next)) { /* 按结果尺度判断收敛。 */
                root = next; /* 保留最新结果。 */
                break; /* 达到容差后停止。 */
            }
            root = next; /* 未收敛时继续迭代。 */
        }
    double sum = 0; /* 莱布尼茨级数累加值。 */
    for (int k = 0; k < 1000000; ++k) { /* 设置额外的循环上限。 */
        double term = (k % 2 ? -1.0 : 1.0) / (2 * k + 1); /* 正负交替，分母为奇数。 */
        if (fabs(term) < 1e-6) /* 首个小于阈值的项不加入。 */
            break; /* 阈值以下的项不累加。 */
        sum += term; /* 累加符合阈值的项。 */
    }
    printf("%.6f %.6f\n", root, 4 * sum); /* 级数乘四得到 π 近似。 */
    return 0; /* 正常结束。 */
}
