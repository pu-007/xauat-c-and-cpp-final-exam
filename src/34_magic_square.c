/* 34_magic_square 奇数阶魔方阵 | ISO C99 | 提高
 * 来源/关系：S1 p33–34 编程23；p99–102另有更多阶数拓展（页码均为 PDF 页码；此文件为重写的教学实现）
 * 输入输出约定：输入奇数n=1..15；输出n×n魔方阵
 * 思想：从首行中间开始向右上走；遇占用则从原位置向下；用模运算处理边界。
 * 复杂度：O(n²)，空间O(n²)
 * 对照 34_magic_square.cpp：C 使用定长二维数组，C++ 使用嵌套 vector。
 * 练习：换一组边界数据，先手算再运行。
 * 学习顺序：先看题目→手算样例→遮住代码独立写→运行测试→比较另一语言。
 */
#include <stdio.h> /* 提供 scanf、printf、putchar；C++ 使用流输入输出。 */
int main(void) {
    int n, a[15][15] = {0}; /* 零表示尚未放数。 */
    if (scanf("%d", &n) != 1 || n < 1 || n > 15 || n % 2 == 0) /* 仅接受指定范围的奇数阶。 */
        return 1; /* 输入无效时退出。 */
    int r = 0, c = n / 2; /* 首行中间是数字 1 的位置。 */
    for (int value = 1; value <= n * n; ++value) { /* 依次放入所有数字。 */
        a[r][c] = value; /* 填写当前位置。 */
        int nr = (r + n - 1) % n, nc = (c + 1) % n; /* 右上越界时绕回。 */
        if (a[nr][nc]) /* 候选位置已被占用。 */
            r = (r + 1) % n; /* 从原位置向下，列不变。 */
        else {
            r = nr; /* 采用候选行。 */
            c = nc; /* 采用候选列。 */
        }
    }
    for (r = 0; r < n; ++r) { /* 按行输出。 */
        for (c = 0; c < n; ++c) /* 每行从第一列开始。 */
            printf("%s%d", c ? " " : "", a[r][c]); /* 首项不加前导空格。 */
        putchar('\n'); /* 当前行结束。 */
    }
    return 0; /* 正常结束。 */
}
