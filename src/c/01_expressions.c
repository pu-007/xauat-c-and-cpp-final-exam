#include <stdio.h>
int main(void) {
    int a = 12, n = 5;
    printf("%d %.1f\n", 5 / 2, 5 / 2.0); /* 整数除法先丢弃小数；之后转浮点也补不回来。 */
    a += a;
    printf("%d ", a);
    a = 12;
    a -= 2;
    printf("%d ", a); /* 原卷各小问独立从12开始。 */
    a = 12;
    a *= 2 + 3;
    printf("%d ", a);
    a = 12;
    a /= a + a;
    printf("%d ", a);
    a = 12;
    a %= (n %= 2);
    printf("%d\n", a);
    int m = 2;
    n = 2;
    int result = (m = 5 > 6) && (n = 7 > 8); /* 左边为0，右边不执行，n仍然是2。 */
    printf("%d %d %d\n", result, m, n);
    int x = 3;
    int old = x++; /* 把修改拆成完整语句；不写 x++ + ++x。 */
    printf("%d %d\n", old, x);
    return 0;
}
