#include <iostream>
int main() {
    std::cout << 5 / 2 << ' ' << 5 / 2.0 << '\n';
    // C++流默认不补 .0；这里的2.5恰好与C版本相同。
    int a = 12, n = 5;
    a += a;
    std::cout << a << ' ';
    a = 12;
    a -= 2;
    std::cout << a << ' ';
    a = 12;
    a *= 2 + 3;
    std::cout << a << ' ';
    a = 12;
    a /= a + a;
    std::cout << a << ' ';
    a = 12;
    a %= (n %= 2);
    std::cout << a << '\n';
    int m = 2;
    n = 2;
    bool result = (m = 5 > 6) && (n = 7 > 8); // C++逻辑结果类型是bool，默认输出0/1。
    std::cout << result << ' ' << m << ' ' << n << '\n';
    int x = 3;
    int old = x++;
    std::cout << old << ' ' << x << '\n';
}
